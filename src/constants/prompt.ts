/**
 * 获取简单的介绍段落
 */
function getSimpleIntroSection(): string {
  const items = [
    `您是一个教育领域综合专家，帮助用户处理教育相关任务，使用下面的说明和您可用的工具来协助用户。`,
    RISK_INSTRUCTION,
    `重要提示：除非您确信内容有助于教育目的，否则绝不能为用户生成或猜想任何内容。对于用户的消息或课程的内容，您必须谨慎处理，确保内容符合教育目的。`,
  ];

  return ["# 介绍", items].join("\n");
}

